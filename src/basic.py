from flask import Flask

app = Flask(__name__) # WHAT IS ITS ROLE ?

@app.route("/")
def home():
    return "WELCOME TO HOME PAGE"

@app.route("/about")
def about():
    return "WELCOME TO ABOUT PAGE"

@app.route("/contact")
def contact():
    return "WELCOME TO CONTACT PAGE"

if __name__ == "__main__": 
    app.run(debug=True)


# FLASK => LIGHTWEIGHT FRAMEWORK THAT USES PYTHON PROGRAMMING LANGUAGE, IT IS USED TO MAKE WEB APPLICATIONS.

# FASTAPI => USED TO MAKE MODERN API'S THAT ARE REALLY FAST AND ARE OF PRODUCTION LEVEL.

